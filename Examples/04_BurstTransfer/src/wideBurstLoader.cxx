#include <cstdlib>
#include <numeric>

#include "hls_stream.h"
#include "hls_vector.h"

void wideBurstLoader(
  const hls::vector<float,16>* input, 
  hls::stream<hls::vector<float,16>>& output
) {
  bool foundSentinel = false;
  std::size_t burstIndex = 0;
  while (true) {
    #pragma HLS PIPELINE off

    for (std::size_t index = 0; index <16; index++) {
      #pragma HLS PIPELINE

      const hls::vector<float,16> numbers = input[(burstIndex *16) + index];

      if (!foundSentinel) {
        output.write(numbers);
      }

      foundSentinel |= std::accumulate(
        numbers.begin(), 
        numbers.end(), 
        false, 
        [](const auto a, const auto b){ 
          return a || (*reinterpret_cast<const int*>(&b) & (1 << 31)); 
        }
      );
    }

    if (foundSentinel) {
      break;
    }

    burstIndex++;
  }
}

